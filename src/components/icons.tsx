import { forwardRef } from 'react'

export { IconContext, type IconProps, type IconWeight }

function createDuotoneIcon(
  BaseIcon: PhosphorIcon,
  slug: string,
  defaults?: Pick<IconProps, 'mirrored' | 'weight'>,
) {
  const Wrapped = forwardRef<SVGSVGElement, IconProps>(function DuotoneIcon(
    { className = '', weight = defaults?.weight ?? 'duotone', mirrored = defaults?.mirrored, ...props },
    ref,
  ) {
    const classes = `ph-duotone ph-${slug}${className ? ` ${className}` : ''}`
    const ariaHidden = props['aria-label'] || props.alt ? undefined : (props['aria-hidden'] ?? true)
    return (
      <BaseIcon
        ref={ref}
        weight={weight}
        mirrored={mirrored}
        className={classes}
        aria-hidden={ariaHidden}
        focusable="false"
        {...props}
      />
    )
  })
  Wrapped.displayName = `Duotone(${slug})`
  return Wrapped
}

