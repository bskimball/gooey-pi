function tokens(p) {
  const a = p.ansi
  const rule = (scope, foreground, fontStyle) => ({ scope, settings: fontStyle ? { foreground, fontStyle } : { foreground } })
  return [
    rule(['comment', 'punctuation.definition.comment', 'string.comment'], a.brightBlack, 'italic'),
    rule(['keyword', 'storage', 'storage.type', 'storage.modifier', 'keyword.control'], a.magenta),
    rule(['keyword.operator', 'punctuation', 'meta.brace', 'punctuation.separator', 'punctuation.terminator'], p.text2),
    rule(['keyword.operator.new', 'keyword.operator.expression', 'keyword.operator.logical.python'], a.magenta),
    rule(['string', 'punctuation.definition.string', 'markup.inline.raw'], a.green),
    rule(['string.regexp', 'constant.character.escape'], a.cyan),
    rule(['constant.numeric', 'constant.language', 'constant.other', 'support.constant', 'variable.other.constant'], a.yellow),
    rule(['entity.name.function', 'support.function', 'meta.function-call', 'variable.function'], a.blue),
    rule(['entity.name.type', 'entity.name.class', 'support.type', 'support.class', 'entity.other.inherited-class', 'entity.name.namespace'], a.cyan),
    rule(['variable', 'variable.other', 'meta.definition.variable'], p.text),
    rule(['variable.parameter'], p.text2, 'italic'),
    rule(['variable.language', 'variable.language.this'], a.red, 'italic'),
    rule(['variable.other.property', 'variable.other.object.property', 'support.variable.property', 'meta.object-literal.key'], p.text2),
    rule(['entity.name.tag', 'punctuation.definition.tag'], a.blue),
    rule(['entity.other.attribute-name'], a.yellow),
    rule(['support.type.property-name.css', 'support.type.property-name.json', 'support.type.property-name'], a.blue),
    rule(['support.type.property-name.json.comments'], a.blue),
    rule(['entity.name.tag.yaml'], a.blue),
    rule(['meta.decorator', 'punctuation.decorator', 'entity.name.function.decorator'], a.yellow),
    rule(['markup.heading', 'entity.name.section'], p.prime, 'bold'),
    rule(['markup.bold'], p.text, 'bold'),
    rule(['markup.italic'], p.text, 'italic'),
    rule(['markup.underline.link', 'string.other.link'], p.prime),
    rule(['markup.quote'], p.text3, 'italic'),
    rule(['markup.list punctuation.definition.list'], a.magenta),
    rule(['markup.inserted'], p.diffAddLine),
    rule(['markup.deleted'], p.diffRemoveLine),
    rule(['markup.changed'], p.prime),
    rule(['invalid', 'invalid.illegal'], p.danger),
  ]
}

const semanticTokenColors = (p) => ({
  parameter: { foreground: p.text2, italic: true },
  property: p.text2,
  'variable.readonly': p.ansi.yellow,
  namespace: p.ansi.cyan,
  type: p.ansi.cyan,
  class: p.ansi.cyan,
  interface: p.ansi.cyan,
  enumMember: p.ansi.yellow,
  function: p.ansi.blue,
  method: p.ansi.blue,
})

mkdirSync(new URL('./themes/', import.meta.url), { recursive: true })
for (const [mode, p] of Object.entries(palettes)) {
  const name = `Pi Desktop ${mode === 'dark' ? 'Dark' : 'Light'}`
  const theme = {
    $schema: 'vscode://schemas/color-theme',
    name,
    type: mode,
    semanticHighlighting: true,
    colors: workbench(p),
    tokenColors: tokens(p),
    semanticTokenColors: semanticTokenColors(p),
  }
  writeFileSync(new URL(`./themes/pi-desktop-${mode}-color-theme.json`, import.meta.url), JSON.stringify(theme, null, 2) + '\n')
  console.log(`wrote ${name}`)
}
